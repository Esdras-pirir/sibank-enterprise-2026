  CREATE OR REPLACE EDITIONABLE FUNCTION "SIBANK"."FN_VALIDAR_USUARIO" (
    p_username IN VARCHAR2,
    p_password IN VARCHAR2
)
RETURN NUMBER
IS
    v_id_usuario   Usuarios.id_usuario%TYPE;
    v_hash_bd      Usuarios.password_hash%TYPE;
    v_activo       Usuarios.activo%TYPE;
    v_hash_ingresado VARCHAR2(256);
BEGIN
    SELECT RAWTOHEX(STANDARD_HASH(p_password, 'SHA256'))
    INTO v_hash_ingresado
    FROM DUAL;

    SELECT id_usuario, password_hash, activo
    INTO v_id_usuario, v_hash_bd, v_activo
    FROM Usuarios
    WHERE username = p_username;

    IF v_activo != 'S' THEN
        RETURN -1; -- usuario inactivo/bloqueado
    END IF;

    IF v_hash_bd = v_hash_ingresado THEN
        RETURN v_id_usuario; -- login correcto
    ELSE
        RETURN -1; -- password incorrecto
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN -1; -- usuario no existe
END fn_validar_usuario;
