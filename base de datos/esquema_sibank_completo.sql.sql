  CREATE OR REPLACE EDITIONABLE PROCEDURE "SIBANK"."SP_APROBAR_PRESTAMO" (
    p_id_prestamo       IN NUMBER,
    p_aprobar           IN VARCHAR2, -- 'S' aprobar, 'N' rechazar
    p_id_empleado       IN NUMBER,
    p_id_usuario_actor  IN NUMBER
)
IS
    v_monto NUMBER(14,2);
    v_plazo NUMBER;
    v_tasa  NUMBER(5,2);
    v_cuenta NUMBER;
    v_cuota NUMBER(12,2);
    v_tasa_mensual NUMBER;
BEGIN
    SELECT monto, plazo_meses, tasa_interes, id_cuenta_desembolso
    INTO v_monto, v_plazo, v_tasa, v_cuenta
    FROM Prestamos
    WHERE id_prestamo = p_id_prestamo;

    IF p_aprobar = 'N' THEN
        UPDATE Prestamos
        SET estado = 'RECHAZADO', id_empleado_aprueba = p_id_empleado, fecha_aprobacion = SYSDATE
        WHERE id_prestamo = p_id_prestamo;

        COMMIT;
        sp_registrar_bitacora(p_id_usuario_actor, 'RECHAZAR_PRESTAMO', 'Prestamos',
            'Prestamo id ' || p_id_prestamo || ' rechazado');
        RETURN;
    END IF;

    -- Calculo de cuota mensual (formula de amortizacion frances simplificada)
    v_tasa_mensual := (v_tasa / 100) / 12;
    v_cuota := ROUND(v_monto * v_tasa_mensual / (1 - POWER(1 + v_tasa_mensual, -v_plazo)), 2);

    UPDATE Prestamos
    SET estado = 'APROBADO',
        id_empleado_aprueba = p_id_empleado,
        fecha_aprobacion = SYSDATE,
        cuota_mensual = v_cuota,
        saldo_pendiente = v_monto
    WHERE id_prestamo = p_id_prestamo;

    -- Desembolsar el prestamo a la cuenta del cliente
    sp_depositar(v_cuenta, v_monto, 'Desembolso de prestamo id ' || p_id_prestamo, p_id_usuario_actor);

    COMMIT;

    sp_registrar_bitacora(p_id_usuario_actor, 'APROBAR_PRESTAMO', 'Prestamos',
        'Prestamo id ' || p_id_prestamo || ' aprobado y desembolsado. Cuota: ' || v_cuota);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20050, 'El prestamo indicado no existe.');
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END sp_aprobar_prestamo;
